/**
 * The pack engine: load a pack.json, generate its tokens.css, check it against
 * CANON.md. Pure functions; the CLI is cli.mjs.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const HERE = path.dirname(fileURLToPath(import.meta.url));
export const PACKS = path.join(HERE, 'packs');
export const FONTS = JSON.parse(fs.readFileSync(path.join(HERE, 'fonts.json'), 'utf8'));

export const ROLES = ['display-1', 'display-2', 'display-3', 'title', 'subhead', 'lead', 'body', 'small', 'label'];
export const DISPLAY = ['display-1', 'display-2', 'display-3'];
export const COLORS = ['ground', 'ground-2', 'tint', 'mid', 'line', 'ink', 'ink-2', 'ink-3', 'accent', 'accent-deep', 'accent-tint', 'action', 'on-action', 'band', 'on-band', 'on-band-2'];

// Fluid range: a phone value at 360, a desktop value at 1320 (the frame of the first shipped system).
export const VW_MIN = 360, VW_MAX = 1320;

export function listPacks() {
  return fs.readdirSync(PACKS).filter((d) => fs.existsSync(path.join(PACKS, d, 'pack.json')));
}

export function loadPack(nameOrPath) {
  const file = fs.existsSync(nameOrPath) && nameOrPath.endsWith('.json') ? nameOrPath : path.join(PACKS, nameOrPath, 'pack.json');
  if (!fs.existsSync(file)) throw new Error('no pack "' + nameOrPath + '". Packs: ' + listPacks().join(', '));
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

const r2 = (n) => Math.round(n * 100) / 100;
const r4 = (n) => Math.round(n * 10000) / 10000;

/**
 * [phone, desktop] px -> rem, or a rem clamp() fluid between VW_MIN and VW_MAX.
 * rem, not px: a visitor who raises the browser's default font size gets larger
 * text and space; px ignores that setting (WCAG 1.4.4). From rhythm.css v0.5.
 * The px pair stays in a comment so the numbers remain readable.
 */
const rem = (px) => `${r4(px / 16)}rem`;
export function fluid([p, d]) {
  if (p === d) return rem(p);
  const slope = (d - p) / (VW_MAX - VW_MIN);
  const icpt = p - slope * VW_MIN;
  return `clamp(${rem(p)}, calc(${rem(icpt)} + ${r4(slope * 100)}vw), ${rem(d)})`;
}

// ---- colour ------------------------------------------------------------------
export function parseColor(s) {
  s = String(s).trim();
  let m;
  if ((m = s.match(/^#([0-9a-f]{3})$/i))) return [...m[1]].map((c) => parseInt(c + c, 16)).concat(1);
  if ((m = s.match(/^#([0-9a-f]{6})$/i))) return [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16)).concat(1);
  if ((m = s.match(/^rgba?\(([^)]+)\)$/i))) { const v = m[1].split(',').map((x) => parseFloat(x)); return [v[0], v[1], v[2], v[3] ?? 1]; }
  throw new Error('unparseable colour ' + s);
}
export const over = (t, u) => [0, 1, 2].map((i) => t[i] * t[3] + u[i] * (1 - t[3])).concat(1);
const lin = (c) => { c /= 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
export const lum = ([r, g, b]) => 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
export const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

/** Every allowed text-on-ground pair, measured. */
export function contrastPairs(pack) {
  const c = Object.fromEntries(COLORS.map((k) => [k, parseColor(pack.color[k])]));
  const out = [];
  for (const [ground, texts] of Object.entries(pack.allow || {})) {
    for (const t of texts) {
      const g = c[ground];
      const fg = over(c[t], g);
      out.push({ ground, text: t, ratio: r2(contrast(fg, g)) });
    }
  }
  return out;
}

// ---- fonts ---------------------------------------------------------------------
export function metric(family, weight) {
  const exact = FONTS.fonts[`${family} ${weight}`];
  if (exact) return { ...exact, exact: true };
  // nearest measured weight of the same family
  const same = Object.values(FONTS.fonts).filter((f) => f.family === family);
  if (!same.length) return null;
  const near = same.sort((a, b) => Math.abs(a.weight - weight) - Math.abs(b.weight - weight))[0];
  return { ...near, exact: false };
}

/** Target in Hebrew characters -> ch for this text face. */
export function measureCh(pack, chars) {
  const m = metric(pack.fonts.text.family, pack.type.body.weight);
  return m ? Math.round(chars / m.perCh) : null;
}

// ---- build ------------------------------------------------------------------------
export function buildCss(pack, { scope = ':root', source = `.claude/skills/system-packs/packs/${pack.name}/pack.json`, classes = false } = {}) {
  const fam = (k) => `'${pack.fonts[k].family}', ${/serif/i.test(pack.fonts[k].family) && !/sans/i.test(pack.fonts[k].family) ? 'serif' : 'sans-serif'}`;
  const L = [];
  L.push(`/* ${pack.name} — ${pack.title}`);
  L.push(`   status: ${pack.status}${pack.from ? ', started from ' + pack.from : ''}. Generated by .claude/skills/system-packs from ${source}; edit that, not this file.`);
  L.push(`   Grammar and laws: .claude/skills/system-packs/CANON.md. Fluid values run from ${VW_MIN}px to ${VW_MAX}px. */`);
  L.push(`${scope}{`);
  L.push(`  --font-display:${fam('display')};`);
  L.push(`  --font-text:${fam('text')};`);
  if (pack.fonts.voice) L.push(`  --font-voice:${fam('voice')};`);
  for (const k of COLORS) L.push(`  --${k}:${pack.color[k]};`);
  for (const role of ROLES) {
    const t = pack.type[role];
    L.push(`  --fs-${role}:${fluid(t.size)}; --w-${role}:${t.weight}; --lh-${role}:${t.lh}; --ff-${role}:var(--font-${t.font});${t.tracking ? ` --ls-${role}:${t.tracking}em;` : ''} /* ${t.size[0] === t.size[1] ? t.size[0] : t.size.join('→')}px */`);
  }
  const mb = measureCh(pack, pack.measure.body), ml = measureCh(pack, pack.measure.lead);
  L.push(`  --measure-body:${mb}ch; /* ${pack.measure.body} Hebrew characters in ${pack.fonts.text.family} */`);
  L.push(`  --measure-lead:${ml}ch; /* ${pack.measure.lead} Hebrew characters */`);
  // The display face's measured metrics (fonts.json): used by .sp-display and by trim compensation.
  const dm = metric(pack.fonts.display.family, pack.type['display-1'].weight);
  if (dm) L.push(`  --glyph-w:${dm.glyph}; --trim-fix:${-dm.trimAirTop}em; /* ${pack.fonts.display.family} ${dm.weight}, measured: glyph width; air text-box-trim leaves above Hebrew */`);
  pack.space.forEach((s, i) => L.push(`  --s${i + 1}:${fluid(s)}; /* ${s[0] === s[1] ? s[0] : s.join('→')}px */`));
  L.push(`  --content:${pack.grid.content}px; --gutter:${fluid(pack.grid.gutter)}; --gap:${fluid(pack.grid.gap)};`);
  L.push(`  --r-sm:${pack.shape['r-sm']}px; --r:${pack.shape.r}px; --r-lg:${pack.shape['r-lg']}px;`);
  L.push(`  --ease:${pack.motion.ease}; --t:${pack.motion.t}ms; --t-slow:${pack.motion['t-slow']}ms;`);
  L.push('}');
  const pairs = contrastPairs(pack).map((p) => `${p.text} on ${p.ground} ${p.ratio}`).join(' · ');
  L.push(`/* measured contrast of every allowed pair: ${pairs} */`);
  if (classes) L.push(classesCss(scope === ':root' ? '' : scope + ' '));
  return L.join('\n') + '\n';
}

/**
 * Opt-in classes, from rhythm.css v0.5, bound to the pack grammar and CANON 6.
 * .sp-flow    running text only (article, FAQ answer, legal): roles on h2/h3/h4/p/li and the
 *             coupling table as margins. The doubled class gives (0,2,0), which beats a theme
 *             rule of one class plus one element (`.entry-content p`); a theme rule with two
 *             classes or an ID still wins, and then the landing-pages wrapper is required.
 * .sp-prose   the body measure.
 * .sp-trim    text-box-trim with the measured Hebrew compensation (CANON 4: L1, off by default).
 * .sp-display a measuring tool: a display heading sized to its region, fill x region width /
 *             (chars x glyph-w). Find the size with it, then freeze a step or a named token.
 * Never grid, section padding or containers: those belong to the composition spec.
 */
export function classesCss(pre = '') {
  const f = `${pre}.sp-flow.sp-flow`;
  return `/* ---- opt-in classes (system-packs; CANON 6 coupling) ---- */
${f} > * { margin-block: 0; }
${f} > * + * { margin-block-start: var(--s5); }
${f} > * + h2 { margin-block-start: var(--s8); }
${f} > * + :is(h3, h4) { margin-block-start: var(--s7); }
${f} > h2 + * { margin-block-start: var(--s5); }
${f} > :is(h3, h4) + * { margin-block-start: var(--s3); }
${f} li + li { margin-block-start: var(--s3); }
${f} figure > figcaption { margin-block-start: var(--s3); }
${pre}.sp-flow h2 { font: var(--w-display-2) var(--fs-display-2)/var(--lh-display-2) var(--ff-display-2); text-wrap: balance; }
${pre}.sp-flow h3 { font: var(--w-display-3) var(--fs-display-3)/var(--lh-display-3) var(--ff-display-3); text-wrap: balance; }
${pre}.sp-flow h4 { font: var(--w-title) var(--fs-title)/var(--lh-title) var(--ff-title); text-wrap: balance; }
${pre}.sp-flow :is(p, li, dd) { font: var(--w-body) var(--fs-body)/var(--lh-body) var(--ff-body); text-wrap: pretty; }
${pre}.sp-flow figcaption { font: var(--w-small) var(--fs-small)/var(--lh-small) var(--ff-small); }
${pre}.sp-prose { max-inline-size: var(--measure-body); }
@supports (text-box: trim-both cap alphabetic) {
  ${pre}.sp-trim :is(h1, h2, h3, h4) { text-box: trim-both cap alphabetic; }
  ${pre}.sp-trim.sp-flow.sp-flow > * + h2 { margin-block-start: calc(var(--s8) + var(--trim-fix)); }
}
${pre}.sp-region { container-type: inline-size; }
${pre}.sp-display {
  --fill: .8; --chars: 18;
  font-weight: var(--w-display-1); line-height: var(--lh-display-1); font-family: var(--ff-display-1); text-wrap: balance;
  font-size: clamp(var(--fs-display-2), calc(var(--fill) * 100cqi / (var(--chars) * var(--glyph-w))), calc(var(--fs-display-1) * 1.3));
}`;
}

export function fontsHref(pack) {
  const fams = {};
  for (const k of ['display', 'text', 'voice']) {
    const f = pack.fonts[k];
    if (!f) continue;
    (fams[f.family] ||= new Set());
    f.weights.forEach((w) => fams[f.family].add(w));
    for (const role of ROLES) if (pack.type[role].font === k) fams[f.family].add(pack.type[role].weight);
  }
  const q = Object.entries(fams).map(([f, ws]) => `family=${f.replace(/ /g, '+')}:wght@${[...ws].sort((a, b) => a - b).join(';')}`).join('&');
  return `https://fonts.googleapis.com/css2?${q}&display=swap`;
}

// ---- check ----------------------------------------------------------------------------
/** CANON floors and rules. Returns { fail: [...], warn: [...], info: [...] }. */
export function check(pack) {
  const fail = [], warn = [], info = [];
  for (const k of COLORS) if (!pack.color?.[k]) fail.push(`colour role missing: ${k}`);
  for (const r of ROLES) if (!pack.type?.[r]) fail.push(`type role missing: ${r}`);
  if (pack.space?.length !== 11) fail.push(`space must have 11 steps (s1..s11), has ${pack.space?.length}`);
  if (fail.length) return { fail, warn, info };

  const T = pack.type;
  const both = (r) => T[r].size;
  // floors
  for (const [role, min] of [['body', 16], ['small', 14], ['label', 12]]) {
    if (Math.min(...both(role)) < min) fail.push(`${role} ${Math.min(...both(role))}px is under the ${min}px floor`);
  }
  // line-heights
  for (const r of DISPLAY) if (T[r].lh < 1.0 || T[r].lh > 1.25) fail.push(`${r} line-height ${T[r].lh} outside 1.0–1.25`);
  for (const r of ['lead', 'body', 'small']) if (T[r].lh < 1.5 || T[r].lh > 1.8) fail.push(`${r} line-height ${T[r].lh} outside 1.5–1.8`);
  // display steps
  for (let i = 0; i < DISPLAY.length - 1; i++) {
    for (const [end, idx] of [['phone', 0], ['desktop', 1]]) {
      const a = T[DISPLAY[i]].size[idx], b = T[DISPLAY[i + 1]].size[idx];
      if (a / b < 1.2) fail.push(`${DISPLAY[i]} / ${DISPLAY[i + 1]} at ${end} is ×${r2(a / b)}, under ×1.2`);
    }
  }
  // title vs body distinction
  for (const [end, idx] of [['phone', 0], ['desktop', 1]]) {
    const ratio = T.title.size[idx] / T.body.size[idx];
    const dw = T.title.weight - T.body.weight;
    if (ratio < 1.5 && dw < 200) warn.push(`title vs body at ${end}: ×${r2(ratio)} and +${dw} weight; leans on colour or coupling`);
  }
  // monotonic sizes down the role list (display-1 .. title), desktop
  for (let i = 0; i < 3; i++) if (T[ROLES[i]].size[1] <= T[ROLES[i + 1]].size[1]) fail.push(`${ROLES[i]} is not larger than ${ROLES[i + 1]} on desktop`);
  // fluid ceiling
  for (const r of ROLES) { const [p, d] = T[r].size; if (d > 2.5 * p) fail.push(`${r} ceiling ${d} > 2.5 × floor ${p}`); }
  // tracking
  for (const r of ROLES) if (T[r].tracking) {
    if (r !== 'label') fail.push(`${r} carries letter-spacing; only label may (CANON 4)`);
    else if (T[r].tracking > 0.06) fail.push(`label tracking ${T[r].tracking}em over 0.06em`);
    else info.push(`label tracked ${T[r].tracking}em (a recorded pack choice)`);
  }
  // space
  pack.space.forEach(([p, d], i) => { if (i < 4 && p !== d) warn.push(`s${i + 1} is fluid; micro steps s1–s4 stay fixed`); });
  for (let i = 1; i < 11; i++) if (pack.space[i][1] <= pack.space[i - 1][1] || pack.space[i][0] < pack.space[i - 1][0]) fail.push(`space s${i + 1} does not grow over s${i}`);
  // measures
  if (pack.measure.body > 65) fail.push(`body measure ${pack.measure.body} Hebrew characters, over ~65`);
  // contrast
  for (const p of contrastPairs(pack)) {
    const need = 4.5;
    if (p.ratio < 3) fail.push(`${p.text} on ${p.ground} ${p.ratio}:1 — fails even large text`);
    else if (p.ratio < need) fail.push(`${p.text} on ${p.ground} ${p.ratio}:1 — under 4.5; allow it only for large text or remove the pair`);
  }
  // fonts measured?
  for (const k of ['display', 'text', 'voice']) {
    const f = pack.fonts[k];
    if (!f) continue;
    for (const w of f.weights) {
      const m = metric(f.family, w);
      if (!m) warn.push(`${f.family} is not in fonts.json; run measure-fonts.mjs "${f.family}:${w}"`);
      else if (!m.exact) info.push(`${f.family} ${w} not measured; nearest ${m.weight} used`);
    }
  }
  return { fail, warn, info };
}

/** Optical equalisation factor when a display face changes (CANON 7). */
export function swapFactor(fromFamily, fromWeight, toFamily, toWeight) {
  const a = metric(fromFamily, fromWeight), b = metric(toFamily, toWeight);
  if (!a || !b) throw new Error('both faces must be in fonts.json');
  return r4(a.hebrew / b.hebrew);
}

/**
 * The rhythm.css v0.5 model as a pack generator: six numbers in, a candidate
 * pack out. Steps are body x ratio^n, fluid between the phone and desktop
 * ratios; roles skip steps on purpose (CANON 3); line-height follows size
 * (1em + .75rem for reading, 1em + .5rem for display, clamped to the canon);
 * density multiplies content and macro space only. Colours come from an
 * existing pack, since rhythm carries none. A starting point for the eye,
 * never a finished pack.
 */
export const STEP_OF = { label: -1, small: -1, body: 0, lead: 1, title: 1, subhead: 2, 'display-3': 3, 'display-2': 5, 'display-1': 7 };
const BASE_SPACE = [[4, 4], [8, 8], [12, 12], [16, 16], [20, 24], [24, 32], [32, 48], [40, 64], [56, 96], [72, 128], [96, 160]];

export function fromRhythm({ name, title, register = '', body = [17, 19], ratio = [1.2, 1.25], density = 1, measure = 60, display, text, colorsFrom = 'institutional' }) {
  const [dFam, dW] = display, tFam = text;
  const step = (n, i) => body[i] * ratio[i] ** n;
  const round = (x) => Math.round(x * 2) / 2;
  const type = {};
  for (const [role, n] of Object.entries(STEP_OF)) {
    let size = [round(step(n, 0)), round(step(n, 1))];
    if (role === 'small') size = size.map((v) => Math.max(14, v));
    if (role === 'label') size = size.map((v) => Math.max(13, Math.min(v, 14)));
    const isDisplay = role.startsWith('display') || role === 'title';
    const lhAt = (px) => (px + (isDisplay ? 8 : 12)) / px;
    let lh = Math.round(lhAt(size[1]) * 100) / 100;
    lh = role === 'title' ? Math.min(1.4, Math.max(1.3, lh)) : isDisplay ? Math.min(1.25, Math.max(1.0, lh)) : Math.min(1.8, Math.max(1.5, lh));
    if (role === 'label') lh = 1.3;
    const weight = role.startsWith('display') ? dW : role === 'title' ? Math.max(600, Math.min(dW, 700)) : role === 'subhead' || role === 'label' ? 600 : 400;
    type[role] = { font: isDisplay ? 'display' : 'text', size, weight, lh };
  }
  const src = loadPack(colorsFrom);
  return {
    name, title: title || name, status: 'candidate',
    provenance: `Generated ${new Date().toLocaleDateString('sv-SE')} from the rhythm model: body ${body.join('→')}px, ratio ${ratio.join('→')}, density ${density}, measure ${measure} Hebrew characters. Colours from ${colorsFrom}. Not tuned by eye.`,
    register,
    fonts: { display: { family: dFam, weights: [dW] }, text: { family: tFam, weights: [400, 600] } },
    color: { ...src.color }, allow: JSON.parse(JSON.stringify(src.allow)),
    type,
    measure: { body: measure, lead: Math.round(measure * 0.75) },
    space: BASE_SPACE.map(([p, d], i) => (i < 4 ? [p, d] : [Math.round(p * density), Math.round(d * density)])),
    grid: { ...src.grid }, shape: { ...src.shape }, motion: { ...src.motion },
  };
}
